"""Annual multi-scale swing structure research for TSMC 2330.

Uses confirmed pivot events generated by the causal ZigZag engine. Retrospective
pivot prices are used only to describe completed wave size/duration; predictors
are sampled separately at pivot date, prior lead dates, and confirmation date.
No scale labels or pivot prices are presented as live signals.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

SCALE_BANDS = (
    ("small", 0.03, 0.08),
    ("medium", 0.08, 0.20),
    ("large", 0.20, float("inf")),
)
LEADS = (1, 3, 5, 10, 20)
FEATURE_PREFIXES = (
    "return_", "distance_sma_", "sma", "trend_", "atr_pct", "rsi", "macd",
    "bb_", "relative_volume", "turnover_ratio", "realized_vol", "volatility_",
    "overnight_gap", "intraday_range", "close_location", "upper_wick",
    "lower_wick", "distance_prior", "bearish_", "bullish_", "ema_",
    "distance_ema_", "stoch_", "cci", "williams_", "plus_di", "minus_di",
    "dx", "adx", "obv_", "mfi", "chaikin_", "volume_sma", "volume_zscore",
    "rolling_vwap", "distance_vwap", "roc_", "ppo", "donchian_",
    "distance_donchian_", "foreign_", "foreign_dealer_", "trust_", "dealer_",
    "institutional_", "broker_",
)
EXCLUDE_FEATURES = {
    "obv", "symbol", "date", "open", "high", "low", "close", "volume",
    "turnover", "corporate_action_window", "atr14",
}


def _scale(amplitude: float) -> str | None:
    for name, lower, upper in SCALE_BANDS:
        if amplitude >= lower and amplitude < upper:
            return name
    return None


def _numeric_features(features: pd.DataFrame) -> list[str]:
    return [
        c for c in features.columns
        if c not in EXCLUDE_FEATURES and c.startswith(FEATURE_PREFIXES)
        and pd.api.types.is_numeric_dtype(features[c])
    ]


def _quantiles(values: pd.Series) -> dict:
    x = pd.to_numeric(values, errors="coerce").replace([np.inf, -np.inf], np.nan).dropna()
    if x.empty:
        return {"n": 0, "median": None, "q25": None, "q75": None}
    return {
        "n": int(len(x)), "median": float(x.median()),
        "q25": float(x.quantile(.25)), "q75": float(x.quantile(.75)),
    }


def build_wave_legs(events: pd.DataFrame, features: pd.DataFrame) -> pd.DataFrame:
    rows = []
    if events.empty:
        return pd.DataFrame()
    dates = pd.to_datetime(features["date"]).reset_index(drop=True)
    for threshold_id, group in events.groupby("threshold_id", sort=True):
        group = group.sort_values(["pivot_index", "confirmation_index"]).reset_index(drop=True)
        for a, b in zip(group.iloc[:-1].to_dict("records"), group.iloc[1:].to_dict("records")):
            if a["type"] == b["type"]:
                continue
            start_i, end_i = int(a["pivot_index"]), int(b["pivot_index"])
            if start_i < 0 or end_i >= len(features) or end_i <= start_i:
                continue
            start_price, end_price = float(a["pivot_price"]), float(b["pivot_price"])
            amplitude = abs(end_price / start_price - 1)
            scale = _scale(amplitude)
            if scale is None:
                continue
            rows.append({
                "threshold_id": threshold_id,
                "start_type": a["type"], "end_type": b["type"],
                "start_date": dates.iloc[start_i].date().isoformat(),
                "end_date": dates.iloc[end_i].date().isoformat(),
                "start_year": int(dates.iloc[start_i].year),
                "end_year": int(dates.iloc[end_i].year),
                "start_month": int(dates.iloc[start_i].month),
                "end_month": int(dates.iloc[end_i].month),
                "start_price": start_price, "end_price": end_price,
                "direction": "UP" if b["type"] == "HIGH" else "DOWN",
                "amplitude_pct": amplitude,
                "duration_sessions": end_i - start_i,
                "amplitude_per_session_pct": amplitude / (end_i - start_i),
                "scale": scale,
                "start_confirmation_lag": int(a["confirmation_lag"]),
                "end_confirmation_lag": int(b["confirmation_lag"]),
            })
    return pd.DataFrame(rows)


def build_pivot_characteristics(
    events: pd.DataFrame, features: pd.DataFrame, legs: pd.DataFrame,
) -> pd.DataFrame:
    rows = []
    if events.empty:
        return pd.DataFrame()
    dates = pd.to_datetime(features["date"]).reset_index(drop=True)
    feature_cols = _numeric_features(features)
    action = features.get(
        "corporate_action_window", pd.Series(False, index=features.index)
    ).fillna(True).astype(bool).to_numpy()
    for threshold_id, group in events.groupby("threshold_id", sort=True):
        group = group.sort_values("pivot_index").reset_index(drop=True)
        threshold_legs = legs.loc[legs["threshold_id"] == threshold_id] if not legs.empty else pd.DataFrame()
        for event in group.to_dict("records"):
            i, ci = int(event["pivot_index"]), int(event["confirmation_index"])
            if i < 0 or ci >= len(features) or i >= len(features) or action[i] or action[ci]:
                continue
            adjacent = threshold_legs.loc[
                (threshold_legs["start_date"] == dates.iloc[i].date().isoformat())
                | (threshold_legs["end_date"] == dates.iloc[i].date().isoformat())
            ] if not threshold_legs.empty else pd.DataFrame()
            for leg in adjacent.to_dict("records") if not adjacent.empty else [{}]:
                row = {
                    "threshold_id": threshold_id,
                    "type": event["type"],
                    "pivot_date": dates.iloc[i].date().isoformat(),
                    "confirmation_date": dates.iloc[ci].date().isoformat(),
                    "year": int(dates.iloc[i].year),
                    "month": int(dates.iloc[i].month),
                    "pivot_index": i,
                    "confirmation_index": ci,
                    "confirmation_lag": int(event["confirmation_lag"]),
                    "reversal_pct": float(event["reversal_pct"]),
                    "adjacent_wave_scale": leg.get("scale"),
                    "adjacent_wave_amplitude_pct": leg.get("amplitude_pct"),
                    "adjacent_wave_duration_sessions": leg.get("duration_sessions"),
                    "adjacent_wave_direction": leg.get("direction"),
                }
                for col in feature_cols:
                    row[f"pivot_{col}"] = features.iloc[i][col]
                    row[f"confirm_{col}"] = features.iloc[ci][col]
                    for lead in LEADS:
                        j = i - lead
                        row[f"lead{lead}_{col}"] = (
                            features.iloc[j][col] if j >= 0 and not action[j] else np.nan
                        )
                rows.append(row)
    return pd.DataFrame(rows)


def _annual_summaries(features: pd.DataFrame, pivots: pd.DataFrame, legs: pd.DataFrame):
    annual = []
    if not features.empty:
        years = sorted(pd.to_datetime(features["date"]).dt.year.unique().tolist())
    else:
        years = []
    for year in years:
        sessions = int((pd.to_datetime(features["date"]).dt.year == year).sum())
        for threshold_id in sorted(pivots["threshold_id"].unique()) if not pivots.empty else []:
            p = pivots.loc[(pivots["year"] == year) & (pivots["threshold_id"] == threshold_id)]
            l = legs.loc[(legs["start_year"] == year) & (legs["threshold_id"] == threshold_id)] if not legs.empty else pd.DataFrame()
            for kind in ("LOW", "HIGH"):
                q = p.loc[p["type"] == kind].drop_duplicates(subset=["pivot_index"])
                annual.append({
                    "year": int(year), "threshold_id": threshold_id, "pivot_type": kind,
                    "trading_sessions": sessions, "pivot_count": int(len(q)),
                    "pivots_per_100_sessions": float(len(q) / sessions * 100) if sessions else None,
                    "median_confirmation_lag": float(q["confirmation_lag"].median()) if len(q) else None,
                    "median_reversal_pct": float(q["reversal_pct"].median()) if len(q) else None,
                })
            for scale in ("small", "medium", "large"):
                scale_rows = l.loc[l["scale"] == scale] if not l.empty else pd.DataFrame()
                for direction in ("UP", "DOWN", "ALL"):
                    q = scale_rows if direction == "ALL" or scale_rows.empty else scale_rows.loc[scale_rows["direction"] == direction]
                    annual.append({
                        "year": int(year), "threshold_id": threshold_id,
                        "pivot_type": f"WAVE_{scale.upper()}_{direction}",
                        "trading_sessions": sessions, "pivot_count": int(len(q)),
                        "pivots_per_100_sessions": float(len(q) / sessions * 100) if sessions else None,
                        "median_confirmation_lag": None, "median_reversal_pct": None,
                        "median_amplitude_pct": float(q["amplitude_pct"].median()) if len(q) else None,
                        "q25_amplitude_pct": float(q["amplitude_pct"].quantile(.25)) if len(q) else None,
                        "q75_amplitude_pct": float(q["amplitude_pct"].quantile(.75)) if len(q) else None,
                        "median_duration_sessions": float(q["duration_sessions"].median()) if len(q) else None,
                        "median_amplitude_per_session_pct": float(q["amplitude_per_session_pct"].median()) if len(q) else None,
                    })
    return pd.DataFrame(annual)


def _indicator_patterns(pivots: pd.DataFrame) -> pd.DataFrame:
    rows = []
    if pivots.empty:
        return pd.DataFrame()
    feature_cols = [
        c for c in pivots.columns
        if c.startswith(("pivot_", "lead1_", "lead3_", "lead5_", "lead10_", "lead20_"))
        and c.rsplit("_", 1)[-1] not in {"date", "index"}
    ]
    for (year, threshold, kind, scale), group in pivots.groupby(
        ["year", "threshold_id", "type", "adjacent_wave_scale"], dropna=False, sort=True
    ):
        row = {
            "year": int(year), "threshold_id": threshold, "pivot_type": kind,
            "adjacent_wave_scale": scale, "events": int(len(group)),
        }
        for col in feature_cols:
            stats = _quantiles(group[col])
            row[f"{col}_n"] = stats["n"]
            row[f"{col}_median"] = stats["median"]
            row[f"{col}_q25"] = stats["q25"]
            row[f"{col}_q75"] = stats["q75"]
        rows.append(row)
    return pd.DataFrame(rows)


def run(features_path: str, events_path: str, output_dir: str) -> dict:
    features = pd.read_csv(features_path)
    events = pd.read_csv(events_path)
    required_features = {"date", "high", "low", "close", "corporate_action_window"}
    required_events = {
        "threshold_id", "type", "pivot_index", "confirmation_index", "pivot_price",
        "pivot_date", "confirmation_date", "confirmation_lag", "reversal_pct",
    }
    if missing := required_features - set(features.columns):
        raise ValueError(f"Feature file missing columns: {sorted(missing)}")
    if missing := required_events - set(events.columns):
        raise ValueError(f"Event file missing columns: {sorted(missing)}")
    features["date"] = pd.to_datetime(features["date"], errors="coerce")
    if features["date"].isna().any():
        raise ValueError("Feature dates contain invalid values")
    features = features.sort_values("date").drop_duplicates("date").reset_index(drop=True)
    events["pivot_index"] = pd.to_numeric(events["pivot_index"], errors="coerce")
    events["confirmation_index"] = pd.to_numeric(events["confirmation_index"], errors="coerce")
    events = events.dropna(subset=["pivot_index", "confirmation_index"]).copy()
    events[["pivot_index", "confirmation_index"]] = events[["pivot_index", "confirmation_index"]].astype(int)
    if events.empty:
        raise ValueError("No valid pivot events")
    if events[["pivot_index", "confirmation_index"]].min().min() < 0 or events["confirmation_index"].max() >= len(features):
        raise ValueError("Pivot indices do not align with feature file")
    for col in ("high", "low", "close"):
        features[col] = pd.to_numeric(features[col], errors="coerce")
    features["corporate_action_window"] = features["corporate_action_window"].fillna(True).astype(bool)
    legs = build_wave_legs(events, features)
    pivots = build_pivot_characteristics(events, features, legs)
    annual = _annual_summaries(features, pivots, legs)
    patterns = _indicator_patterns(pivots)
    monthly = (
        pivots.groupby(["month", "type", "adjacent_wave_scale"], dropna=False)
        .agg(pivot_wave_associations=("pivot_index", "size"),
             unique_pivots=("pivot_index", "nunique")).reset_index()
        if not pivots.empty else pd.DataFrame()
    )
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    legs.to_csv(out / "tsmc_2330_annual_wave_legs.csv", index=False)
    pivots.to_csv(out / "tsmc_2330_annual_pivot_characteristics.csv", index=False)
    annual.to_csv(out / "tsmc_2330_annual_scale_summary.csv", index=False)
    patterns.to_csv(out / "tsmc_2330_annual_indicator_patterns.csv", index=False)
    monthly.to_csv(out / "tsmc_2330_monthly_pivot_distribution.csv", index=False)
    summary = {
        "symbol": "2330", "analysis": "annual small/medium/large swing highs and lows",
        "scale_bands": [
            {"name": name, "lower_amplitude_pct": lo, "upper_amplitude_pct": hi if np.isfinite(hi) else None}
            for name, lo, hi in SCALE_BANDS
        ],
        "lead_sessions": list(LEADS),
        "threshold_ids": sorted(events["threshold_id"].astype(str).unique().tolist()),
        "years": sorted(pd.to_datetime(features["date"]).dt.year.unique().astype(int).tolist()),
        "wave_legs": int(len(legs)), "pivot_characteristics": int(len(pivots)),
        "annual_summary_rows": int(len(annual)), "indicator_pattern_rows": int(len(patterns)),
        "outputs": [
            "tsmc_2330_annual_wave_legs.csv",
            "tsmc_2330_annual_pivot_characteristics.csv",
            "tsmc_2330_annual_scale_summary.csv",
            "tsmc_2330_annual_indicator_patterns.csv",
            "tsmc_2330_monthly_pivot_distribution.csv",
        ],
        "interpretation": {
            "wave_scale": "retrospective adjacent pivot-leg amplitude; small 3-8%, medium 8-20%, large >=20%",
            "pivot_features": "pivot-day descriptors and lead-session features are retrospective diagnostics; confirmation-day features are available only after the causal confirmation date",
            "annual_comparison": "yearly pivot counts normalized by observed trading sessions; wave amplitude and duration summarized by year",
            "not_a_strategy": True,
        },
        "warning": "Wave scale is assigned using completed future leg amplitude and is for descriptive research only. Never use it as a live signal or as a training feature. Confirmation features are not available at the retrospective pivot date. Latest year may be partial.",
    }
    (out / "tsmc_2330_annual_swing_scale_research.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2, default=float), encoding="utf-8"
    )
    return summary


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--features", required=True)
    parser.add_argument("--events", required=True)
    parser.add_argument("--output", default="artifacts/tsmc_2330_swing")
    args = parser.parse_args()
    print(json.dumps(run(args.features, args.events, args.output), ensure_ascii=False, indent=2, default=float))


if __name__ == "__main__":
    main()
