"""Deterministic 500-wave sample study, isolated from legacy TSMC research outputs.

Wave labels are retrospective. Predictors are sampled only at the start-pivot
confirmation close, when the pivot has become causally confirmed. The random
sample is selected with a fixed seed, then split chronologically with overlap
purging so validation outcomes do not leak into research.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, balanced_accuracy_score, confusion_matrix
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from tsmc_2330_annual_swing_scale_research import build_wave_legs

SEED = 23302026
SAMPLE_SIZE = 500
RESEARCH_FRACTION = 0.70
EXCLUDED = {
    "open", "high", "low", "close", "volume", "turnover", "symbol", "date",
    "corporate_action_window", "atr14", "obv",
}


def make_wave_population(events: pd.DataFrame, features: pd.DataFrame) -> pd.DataFrame:
    legs = build_wave_legs(events, features)
    if legs.empty:
        raise ValueError("No completed alternating pivot-to-pivot waves found")
    # Resolve the start pivot index explicitly; never use the endpoint's future data.
    # A threshold can have many pivots. Match the leg's exact start date to its pivot.
    events_dates = pd.to_datetime(events["pivot_date"]).dt.date.astype(str)
    event_lookup = events.assign(_pivot_date=events_dates).drop_duplicates(
        ["threshold_id", "_pivot_date"]
    ).set_index(["threshold_id", "_pivot_date"])
    confirm_idx = []
    confirm_date = []
    confirm_lag = []
    for row in legs.itertuples(index=False):
        key = (row.threshold_id, row.start_date)
        if key not in event_lookup.index:
            confirm_idx.append(np.nan)
            confirm_date.append(None)
            confirm_lag.append(np.nan)
        else:
            e = event_lookup.loc[key]
            if isinstance(e, pd.DataFrame):
                e = e.iloc[0]
            confirm_idx.append(int(e["confirmation_index"]))
            confirm_date.append(str(e["confirmation_date"]))
            confirm_lag.append(int(e["confirmation_lag"]))
    legs = legs.copy()
    legs["start_confirmation_index"] = confirm_idx
    legs["start_confirmation_date"] = confirm_date
    legs["start_confirmation_lag"] = confirm_lag
    legs = legs.dropna(subset=["start_confirmation_index", "start_confirmation_date"])
    legs["start_confirmation_index"] = legs["start_confirmation_index"].astype(int)
    # Same dated move can be generated by several pivot thresholds. Keep one
    # canonical row per actual date/direction; threshold is retained for audit.
    legs = legs.sort_values(["start_date", "end_date", "direction", "threshold_id"])
    legs = legs.drop_duplicates(["start_date", "end_date", "direction"], keep="first")
    return legs.reset_index(drop=True)


def deterministic_sample(waves: pd.DataFrame, n: int = SAMPLE_SIZE, seed: int = SEED) -> pd.DataFrame:
    if len(waves) < n:
        raise ValueError(f"Need at least {n} unique completed waves; found {len(waves)}")
    sampled = waves.sample(n=n, random_state=seed).copy()
    return sampled.sort_values(["start_confirmation_date", "end_date"]).reset_index(drop=True)


def chronological_split(sample: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, str]:
    ordered = sample.sort_values(["start_confirmation_date", "end_date"]).reset_index(drop=True)
    cut = int(np.floor(len(ordered) * RESEARCH_FRACTION))
    if cut < 2 or cut >= len(ordered):
        raise ValueError("Insufficient sample for chronological research/validation split")
    validation_start = str(ordered.iloc[cut]["start_confirmation_date"])
    validation = ordered.iloc[cut:].copy()
    # Purge research waves whose completed outcome overlaps the validation era.
    research = ordered.iloc[:cut].copy()
    research = research.loc[research["end_date"] < validation_start].copy()
    if len(research) < 25 or len(validation) < 25:
        raise ValueError(
            f"Insufficient data after overlap purge: research={len(research)}, "
            f"validation={len(validation)}"
        )
    return research.reset_index(drop=True), validation.reset_index(drop=True), validation_start


def attach_causal_features(waves: pd.DataFrame, features: pd.DataFrame) -> tuple[pd.DataFrame, list[str]]:
    numeric = [
        col for col in features.columns
        if col not in EXCLUDED and pd.api.types.is_numeric_dtype(features[col])
        and not col.startswith(("future_", "label_", "pivot_", "confirm_", "lead"))
    ]
    if "close" not in features.columns:
        raise ValueError("Feature file must contain adjusted close for forward target calculation")
    matrix = features[numeric].reset_index(drop=True)
    adjusted_close = pd.to_numeric(features["close"], errors="coerce").reset_index(drop=True)
    action = features.get(
        "corporate_action_window", pd.Series(False, index=features.index)
    ).fillna(True).astype(bool).to_numpy()
    rows = []
    for wave in waves.to_dict("records"):
        idx = int(wave["start_confirmation_index"])
        if idx < 0 or idx >= len(matrix) or action[idx]:
            continue
        if pd.Timestamp(wave["start_confirmation_date"]) >= pd.Timestamp(wave["end_date"]):
            continue
        close_at_confirmation = adjusted_close.iloc[idx]
        if pd.isna(close_at_confirmation) or close_at_confirmation <= 0:
            continue
        future_return = float(wave["end_price"] / close_at_confirmation - 1.0)
        future_direction = "UP" if future_return > 0 else ("DOWN" if future_return < 0 else "FLAT")
        values = matrix.iloc[idx].to_dict()
        if not any(pd.notna(v) for v in values.values()):
            continue
        rows.append({
            **wave,
            "confirmation_close": float(close_at_confirmation),
            "post_confirmation_return_pct": future_return,
            "post_confirmation_direction": future_direction,
            **{f"feature__{k}": v for k, v in values.items()},
        })
    out = pd.DataFrame(rows)
    feature_cols = [col for col in out.columns if col.startswith("feature__")]
    return out, feature_cols

def descriptive_metrics(frame: pd.DataFrame) -> dict:
    if frame.empty:
        return {"n": 0}
    result = {
        "n": int(len(frame)),
        "pivot_to_pivot_up_share": float((frame["direction"] == "UP").mean()),
        "median_pivot_to_pivot_amplitude_pct": float(frame["amplitude_pct"].median()),
        "median_duration_sessions": float(frame["duration_sessions"].median()),
        "scale_counts": {
            str(k): int(v) for k, v in frame["scale"].value_counts().sort_index().items()
        },
        "pivot_direction_scale": {
            f"{direction}_{scale}": int(len(g))
            for (direction, scale), g in frame.groupby(["direction", "scale"])
        },
    }
    if "post_confirmation_direction" in frame:
        result["post_confirmation_direction_counts"] = {
            str(k): int(v) for k, v in frame["post_confirmation_direction"].value_counts().sort_index().items()
        }
        result["median_post_confirmation_return_pct"] = float(frame["post_confirmation_return_pct"].median())
        result["mean_post_confirmation_return_pct"] = float(frame["post_confirmation_return_pct"].mean())
    return result


def overlap_diagnostics(frame: pd.DataFrame) -> dict:
    if frame.empty:
        return {"n": 0, "overlap_clusters": 0, "largest_cluster": 0}
    ordered = frame.assign(
        _start=pd.to_datetime(frame["start_confirmation_date"]),
        _end=pd.to_datetime(frame["end_date"]),
    ).sort_values(["_start", "_end"])
    clusters, current, current_end = [], [], None
    for idx, row in ordered.iterrows():
        if current and row["_start"] > current_end:
            clusters.append(current)
            current, current_end = [], None
        current.append(idx)
        current_end = row["_end"] if current_end is None else max(current_end, row["_end"])
    if current:
        clusters.append(current)
    sizes = [len(x) for x in clusters]
    return {
        "n": int(len(frame)),
        "unique_confirmation_dates": int(frame["start_confirmation_date"].nunique()),
        "unique_endpoint_dates": int(frame["end_date"].nunique()),
        "overlap_clusters": int(len(clusters)),
        "largest_cluster": int(max(sizes)),
        "rows_in_multiwave_clusters": int(sum(x for x in sizes if x > 1)),
        "interpretation": "Overlapping waves are dependent observations; row-level metrics are not independent-trial estimates.",
    }

def run(features_path: str, events_path: str, output_dir: str) -> dict:
    features = pd.read_csv(features_path)
    events = pd.read_csv(events_path)
    required_events = {
        "threshold_id", "type", "pivot_index", "confirmation_index",
        "pivot_date", "confirmation_date", "confirmation_lag",
    }
    missing = required_events - set(events.columns)
    if missing:
        raise ValueError(f"Pivot event file missing columns: {sorted(missing)}")
    features["date"] = pd.to_datetime(features["date"], errors="raise")
    events["pivot_index"] = pd.to_numeric(events["pivot_index"], errors="coerce")
    events["confirmation_index"] = pd.to_numeric(events["confirmation_index"], errors="coerce")
    events = events.dropna(subset=["pivot_index", "confirmation_index"]).copy()
    events[["pivot_index", "confirmation_index"]] = events[
        ["pivot_index", "confirmation_index"]
    ].astype(int)
    events = events.sort_values(["threshold_id", "pivot_index"]).reset_index(drop=True)
    if events.empty:
        raise ValueError("No valid pivot events")
    if events["confirmation_index"].max() >= len(features):
        raise ValueError("Pivot event indices do not align with causal feature rows")

    population_all = make_wave_population(events, features)
    causal_mask = pd.to_datetime(population_all["start_confirmation_date"]) < pd.to_datetime(population_all["end_date"])
    idx = population_all["start_confirmation_index"].astype(int).to_numpy()
    action = features.get(
        "corporate_action_window", pd.Series(False, index=features.index)
    ).fillna(True).astype(bool).to_numpy()
    adjusted_close = pd.to_numeric(features["close"], errors="coerce").to_numpy()
    data_ok = np.array([
        0 <= i < len(features) and not action[i] and pd.notna(adjusted_close[i]) and adjusted_close[i] > 0
        for i in idx
    ])
    population = population_all.loc[causal_mask.to_numpy() & data_ok].copy().reset_index(drop=True)
    excluded_noncausal = int(len(population_all) - len(population))
    sample = deterministic_sample(population)
    research, validation, validation_start = chronological_split(sample)
    research_x, feature_cols = attach_causal_features(research, features)
    validation_x, _ = attach_causal_features(validation, features)
    # Keep a common, predeclared feature set; no feature selection on validation.
    feature_cols = [
        c for c in feature_cols
        if c in validation_x.columns and research_x[c].notna().any()
    ]
    research_x = research_x.dropna(subset=["post_confirmation_direction"])
    validation_x = validation_x.dropna(subset=["post_confirmation_direction"])
    if research_x["post_confirmation_direction"].nunique() < 2 or validation_x.empty:
        raise ValueError("Insufficient forward directional classes for independent validation")

    model = make_pipeline(
        SimpleImputer(strategy="median", add_indicator=True),
        StandardScaler(),
        LogisticRegression(max_iter=2000, class_weight="balanced", random_state=SEED),
    )
    model.fit(research_x[feature_cols], research_x["post_confirmation_direction"])
    predicted = model.predict(validation_x[feature_cols])
    actual = validation_x["post_confirmation_direction"].to_numpy()
    labels = sorted(set(actual) | set(predicted))
    class_counts = pd.Series(actual).value_counts(normalize=True)
    validation_x["predicted_post_confirmation_direction"] = predicted
    validation_x["prediction_correct"] = (actual == predicted)
    pivot_baseline = np.where(validation_x["start_type"].to_numpy() == "LOW", "UP", "DOWN")
    validation_x["pivot_type_baseline_prediction"] = pivot_baseline
    validation_x["pivot_type_baseline_correct"] = (actual == pivot_baseline)
    validation_x["validation_year"] = pd.to_datetime(validation_x["start_confirmation_date"]).dt.year
    latest_data_year = int(pd.to_datetime(features["date"]).dt.year.max())
    yearly_metrics = []
    for year, group in validation_x.groupby("validation_year", sort=True):
        yearly_metrics.append({
            "year": int(year),
            "n": int(len(group)),
            "accuracy": float(accuracy_score(group["post_confirmation_direction"], group["predicted_post_confirmation_direction"])),
            "balanced_accuracy": float(balanced_accuracy_score(group["post_confirmation_direction"], group["predicted_post_confirmation_direction"])),
            "pivot_type_baseline_accuracy": float(accuracy_score(group["post_confirmation_direction"], group["pivot_type_baseline_prediction"])),
            "is_latest_data_year_partial": bool(int(year) == latest_data_year),
        })
    validation_model = {
        "n": int(len(actual)),
        "accuracy": float(accuracy_score(actual, predicted)),
        "balanced_accuracy": float(balanced_accuracy_score(actual, predicted)),
        "majority_class_baseline_accuracy": float(class_counts.max()),
        "pivot_type_baseline_accuracy": float(accuracy_score(actual, pivot_baseline)),
        "pivot_type_baseline_balanced_accuracy": float(balanced_accuracy_score(actual, pivot_baseline)),
        "model_beats_pivot_type_baseline": bool(accuracy_score(actual, predicted) > accuracy_score(actual, pivot_baseline)),
        "pivot_type_baseline_confusion_matrix": confusion_matrix(actual, pivot_baseline, labels=labels).tolist(),
        "labels": labels,
        "confusion_matrix": confusion_matrix(actual, predicted, labels=labels).tolist(),
        "model": "median-imputed standardized logistic regression, class_weight=balanced",
        "features": feature_cols,
        "feature_count": len(feature_cols),
        "predictor_timing": "start-pivot confirmation close; target is strictly after the confirmation date",
        "target": "sign(end_pivot_adjusted_price / adjusted_close_at_start_confirmation - 1)",
    }

    sample_out, _ = attach_causal_features(sample, features)
    research_keys = set(zip(research["start_date"], research["end_date"], research["direction"]))
    validation_keys = set(zip(validation["start_date"], validation["end_date"], validation["direction"]))
    sample_out["sample_role"] = [
        "research" if (r.start_date, r.end_date, r.direction) in research_keys
        else ("validation" if (r.start_date, r.end_date, r.direction) in validation_keys
              else "purged_overlap")
        for r in sample_out.itertuples(index=False)
    ]
    research_x["sample_role"] = "research"
    validation_x["sample_role"] = "validation"
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    sample_out.to_csv(out / "tsmc_2330_random_500_wave_sample.csv", index=False)
    research_x.to_csv(out / "tsmc_2330_random_500_wave_research.csv", index=False)
    validation_x.to_csv(out / "tsmc_2330_random_500_wave_validation.csv", index=False)

    summary = {
        "symbol": "2330",
        "period": [
            str(pd.to_datetime(features["date"]).min().date()),
            str(pd.to_datetime(features["date"]).max().date()),
        ],
        "population_unique_waves_before_causal_filter": int(len(population_all)),
        "excluded_noncausal_waves": excluded_noncausal,
        "causally_eligible_population": int(len(population)),
        "sample_size": int(len(sample_out)),
        "random_seed": SEED,
        "sampling": "uniform random sample without replacement from waves whose start-pivot confirmation precedes the endpoint",
        "split": {
            "method": "chronological 70/30 after deterministic random sampling",
            "validation_start_confirmation_date": validation_start,
            "research_count_after_overlap_purge": int(len(research_x)),
            "validation_count": int(len(validation_x)),
            "purge_rule": "remove research wave if its end_date is on or after the first validation start-pivot confirmation date",
        },
        "research_descriptive": descriptive_metrics(research_x),
        "validation_descriptive": descriptive_metrics(validation_x),
        "validation_overlap_diagnostics": overlap_diagnostics(validation_x),
        "validation_yearly_metrics": yearly_metrics,
        "validation_direction_model": validation_model,
        "limitations": [
            "Completed wave endpoints are retrospective labels, not tradable entry/exit signals.",
            "Waves whose start-pivot confirmation is on or after the endpoint are excluded before sampling.",
            "Predictors are frozen at the start-pivot confirmation close; the target is strictly after that date.",
            "Overlapping waves are dependent observations; validation row counts are not independent-trial counts.",
            "This study predicts movement to a retrospective endpoint; it does not establish executable CAGR or win rate.",
        ],
        "target_status": "NOT_APPLICABLE: this forward-direction diagnostic does not replace executable strategy CAGR/win-rate validation.",
    }
    (out / "tsmc_2330_random_500_wave_study.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2, default=float), encoding="utf-8"
    )
    return summary


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--features", required=True)
    parser.add_argument("--events", required=True)
    parser.add_argument("--output", default="artifacts/tsmc_2330_random_500_wave")
    args = parser.parse_args()
    print(json.dumps(run(args.features, args.events, args.output), ensure_ascii=False, indent=2, default=float))


if __name__ == "__main__":
    main()
